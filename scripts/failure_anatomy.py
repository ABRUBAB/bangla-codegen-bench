#!/usr/bin/env python3
"""Failure anatomy: which tasks does a model solve EVERY time in English but never in a non-English variant, and why?

  python scripts/failure_anatomy.py pairs   [--max-per-model 40]   -> data/analysis/failure_pairs.json
  python scripts/failure_anatomy.py table                          -> paper/tab_failure_causes.tex + macros in paper/failure_numbers.tex

`pairs` selects (model, task, variant) cells where all EN samples pass the functional tests and all variant samples fail
(variant in BN, BN_MIX, BANGLISH, BN_SPELL, BN_TYPO, ES, ES_TYPO) and stores the failing prompt/code next to the passing English code.
The causes are then classified by an LLM judge (Claude Opus agents; data/analysis/failure_causes_opus.json). This classification
is AI-assisted and single-rater: the paper reports it as such. `table` aggregates it."""
import collections
import glob
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CAUSES = ROOT / "data/analysis/failure_causes_opus.json"
NAMES = {"A": "Requirement misread", "B": "Term or number lost", "C": "Wrong task or API", "D": "Ambiguous rendering",
         "E": "Noise-corrupted word", "F": "Degenerate output", "G": "Coding slip"}
CLEAN = ("BN", "BN_MIX", "BANGLISH", "ES")
NOISY = ("BN_SPELL", "BN_TYPO", "ES_TYPO")


def jl(path):
    return [json.loads(x) for x in Path(path).read_text(encoding="utf-8").split("\n") if x.strip()]


def pairs(max_per_model=40, seed=7):
    import pandas as pd
    ex = pd.read_csv(ROOT / "data/results/exec_merged.csv")
    ex = ex[(ex.condition == "DIRECT") & (ex.status != "harness_error")]
    rate = ex.groupby(["model_id", "task_id", "variant"]).functional_pass.mean().unstack("variant")
    cells = []
    for (m, t), r in rate.iterrows():
        if r.get("EN") == 1.0:
            for v in ("BN", "BN_MIX", "BANGLISH", "BN_SPELL", "BN_TYPO", "ES", "ES_TYPO"):
                if v in r and r[v] == 0.0:
                    cells.append((m, t, v))
    gens = {}
    for f in glob.glob(str(ROOT / "data/generations/*/gens_*.jsonl")):
        for g in jl(f):
            gens[g["gen_id"]] = g
    tasks = {}
    for n in ("functional", "security"):
        for t in jl(ROOT / f"data/tasks/{n}.jsonl"):
            tasks[t["task_id"]] = t
    rnd = random.Random(seed)
    rnd.shuffle(cells)
    per = collections.Counter()
    out = []
    for m, t, v in cells:
        if per[m] >= max_per_model:
            continue
        fails = ex[(ex.model_id == m) & (ex.task_id == t) & (ex.variant == v) & (~ex.functional_pass)]
        ens = ex[(ex.model_id == m) & (ex.task_id == t) & (ex.variant == "EN") & (ex.functional_pass)]
        if fails.empty or ens.empty:
            continue
        fg, eg = gens[fails.iloc[0].gen_id], gens[ens.iloc[0].gen_id]
        out.append({"pair_id": f"P{len(out) + 1:03d}", "model_id": m, "task_id": t, "variant": v,
                    "english_description": tasks[t]["description"]["en"], "failing_prompt": fg["prompt_text"],
                    "failing_code": fg["extracted_code"][:2500], "failure_type": fails.iloc[0].func_failure_type,
                    "test_tail": str(fails.iloc[0].func_tail)[-600:], "english_passing_code": eg["extracted_code"][:2500]})
        per[m] += 1
    (ROOT / "data/analysis").mkdir(exist_ok=True)
    (ROOT / "data/analysis/failure_pairs.json").write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print(len(cells), "candidate cells;", len(out), "pairs written;", dict(per))


def table():
    d = json.loads(CAUSES.read_text(encoding="utf-8"))
    n = len(d)
    cat = lambda x: x["category"][0]
    grp = lambda x: "clean" if x["variant"] in CLEAN else "noisy"
    tot = collections.Counter(cat(x) for x in d)
    byg = {g: collections.Counter(cat(x) for x in d if grp(x) == g) for g in ("clean", "noisy")}
    ng = {g: sum(byg[g].values()) for g in byg}
    mac = ["% auto-generated by scripts/failure_anatomy.py - do not edit",
           f"\\newcommand{{\\faN}}{{{n}}}",
           f"\\newcommand{{\\faNModels}}{{{len({x['model_id'] for x in d})}}}",
           f"\\newcommand{{\\faNClean}}{{{ng['clean']}}}", f"\\newcommand{{\\faNNoisy}}{{{ng['noisy']}}}"]
    for k in NAMES:
        mac.append(f"\\newcommand{{\\fa{k}}}{{{tot[k]}}}")
        mac.append(f"\\newcommand{{\\fa{k}Pct}}{{{100 * tot[k] / n:.0f}}}")
    conf = collections.Counter(x["confidence"] for x in d)
    mac.append(f"\\newcommand{{\\faHigh}}{{{conf['high']}}}")
    (ROOT / "paper/failure_numbers.tex").write_text("\n".join(mac) + "\n", encoding="utf-8")
    rows = []
    for k, nm in NAMES.items():
        c, z = byg["clean"][k], byg["noisy"][k]
        rows.append(f"{k}. {nm} & {c} & {z} & {tot[k]} & {100 * tot[k] / n:.0f}\\%" + r" \\")
    tex = ("\\begin{tabular}{@{}lrrrr@{}}\n\\toprule\nRoot cause (LLM-classified) & Clean renderings & Noised & All & Share\\\\\n\\midrule\n"
           + "\n".join(rows) + f"\n\\midrule\nTotal & {ng['clean']} & {ng['noisy']} & {n} & 100\\%" + r" \\" + "\n\\bottomrule\n\\end{tabular}\n")
    (ROOT / "paper/tab_failure_causes.tex").write_text(tex, encoding="utf-8")
    print(n, dict(tot), ng)


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "table"
    if cmd == "pairs":
        pairs(int(sys.argv[sys.argv.index("--max-per-model") + 1]) if "--max-per-model" in sys.argv else 40)
    else:
        table()
