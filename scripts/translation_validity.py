#!/usr/bin/env python3
"""How often is the model's own 'translation to English' an actual English task description?

For every model and source variant, the translation (data/generations/<model>/translations.jsonl, signature re-injection excluded
because it is appended by the harness) is classified as
  valid         >= 8 English words of prose outside code blocks and < 5 % Bengali script,
  code_only     less than 8 words of prose (the model answered with code instead of translating),
  untranslated  prose still mostly in Bengali script.
Writes data/results/tab_translation_validity.csv and paper/translation_numbers.tex (macros \\tv<Model><Variant>)."""
import glob
import json
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
FENCE = re.compile(r"```.*?```", re.S)
BN = re.compile(r"[ঀ-৿]")
KEY = {"qwen2.5-coder-1.5b": "A", "qwen2.5-coder-3b": "B", "qwen2.5-coder-7b": "C", "deepseek-coder-6.7b": "D",
       "qwen3-8b": "E", "tigercoder-1b": "F", "gemini-3.1-flash-lite": "G", "qwen2.5-coder-14b": "H", "qwen2.5-coder-32b": "I"}


def classify(text: str, sig_reinjected: bool) -> str:
    t = text
    if sig_reinjected:  # the harness appended the signature block; do not count it
        t = text.rsplit("```python", 1)[0]
    prose = FENCE.sub(" ", t)
    prose = re.sub(r"```.*$", " ", prose, flags=re.S)  # unterminated fence
    words = [w for w in re.findall(r"[A-Za-z]+", prose)]
    letters = len(re.findall(r"[A-Za-zঀ-৿]", prose)) or 1
    if len(BN.findall(prose)) / letters >= 0.05:
        return "untranslated"
    return "valid" if len(words) >= 8 else "code_only"


def main():
    rows = []
    for f in sorted(glob.glob(str(ROOT / "data/generations/*/translations.jsonl"))):
        model = Path(f).parent.name
        for line in Path(f).read_text(encoding="utf-8").split("\n"):
            if line.strip():
                r = json.loads(line)
                rows.append({"model": model, "variant": r["variant"], "cls": classify(r["translation"], r["sig_reinjected"])})
    df = pd.DataFrame(rows)
    tab = (df.groupby(["model", "variant"]).cls.value_counts(normalize=True).unstack(fill_value=0) * 100).round(1)
    for c in ("valid", "code_only", "untranslated"):
        if c not in tab:
            tab[c] = 0.0
    tab.to_csv(ROOT / "data/results/tab_translation_validity.csv")
    mac = ["% auto-generated by scripts/translation_validity.py - do not edit"]
    for (m, v), r in tab.iterrows():
        k = KEY.get(m, re.sub(r"[^A-Za-z]", "", m))
        mac.append(f"\\expandafter\\def\\csname tv@{k}@{v.replace('_', '')}\\endcsname{{{r['valid']:.0f}}}")
    mac.append("\\newcommand{\\TV}[2]{\\csname tv@#1@#2\\endcsname}")
    (ROOT / "paper/translation_numbers.tex").write_text("\n".join(mac) + "\n", encoding="utf-8")
    print(tab[["valid", "code_only", "untranslated"]].to_string())


if __name__ == "__main__":
    main()
