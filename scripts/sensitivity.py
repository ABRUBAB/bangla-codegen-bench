#!/usr/bin/env python3
"""Sensitivity of the headline contrasts to the two renderings flagged as ambiguous by the failure analysis (data/audit/errata.md).

Reports, per model and averaged over models, the BN-EN and Spanish-EN functional Pass@1 gaps (percentage points) with all tasks
and after dropping F082 (functional suite) and S009 (security suite). Writes paper/sensitivity_numbers.tex (macros) and
data/results/sensitivity.csv."""
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DROP = {"F082", "S009"}
VARS = ("BN", "BN_MIX", "BANGLISH", "ES", "BN_SPELL", "BN_TYPO")


def gaps(ex, drop):
    d = ex[(ex.condition == "DIRECT") & (ex.status != "harness_error")]
    d = d[~d.task_id.isin(drop)]
    f = d[d.kind == "functional"]
    pt = f.groupby(["model_id", "task_id", "variant"]).functional_pass.mean().reset_index()
    out = {}
    for m, g in pt.groupby("model_id"):
        piv = g.pivot(index="task_id", columns="variant", values="functional_pass")
        for v in VARS:
            if v in piv and "EN" in piv:
                ok = piv[["EN", v]].dropna()
                out[(m, v)] = 100 * (ok[v].mean() - ok["EN"].mean())
    return out


def main():
    ex = pd.read_csv(ROOT / "data/results/exec_merged.csv")
    a, b = gaps(ex, set()), gaps(ex, DROP)
    rows = [{"model_id": m, "variant": v, "gap_all_pp": a[(m, v)], "gap_excl_pp": b[(m, v)]} for (m, v) in a]
    df = pd.DataFrame(rows)
    df.to_csv(ROOT / "data/results/sensitivity.csv", index=False)
    mac = ["% auto-generated by scripts/sensitivity.py - do not edit"]
    for v in VARS:
        s = df[df.variant == v]
        key = v.replace("_", "")
        mac.append(f"\\newcommand{{\\sensAll{key}}}{{{s.gap_all_pp.mean():+.1f}}}")
        mac.append(f"\\newcommand{{\\sensExcl{key}}}{{{s.gap_excl_pp.mean():+.1f}}}")
    (ROOT / "paper/sensitivity_numbers.tex").write_text("\n".join(mac).replace("+-", "-") + "\n", encoding="utf-8")
    print(df.groupby("variant")[["gap_all_pp", "gap_excl_pp"]].mean().round(2))


if __name__ == "__main__":
    main()
