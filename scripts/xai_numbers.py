#!/usr/bin/env python3
"""Numbers for the white-box probes of RQ5 (data/xai/xai_<model>.jsonl and *_hidden.npz) -> paper/xai_numbers.tex.

For each probed model M (key letter as in the other macros) and variant V:
  \\XN{M}{V}{nll}    median change of the reference solution's per-token NLL versus EN (nats/token), over tasks
  \\XN{M}{V}{sig}    share (%) of prompt saliency on the signature,  \\XN{M}{V}{desc}  on the description
  \\XN{M}{V}{cos}    mean cosine similarity to EN of the last-prompt-token state, mean over the last quarter of the layers
and \\XN{M}{all}{rho} / {rhop}: Spearman correlation between late-layer EN-BN alignment and the per-task BN accuracy drop."""
import json
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats as sps

ROOT = Path(__file__).resolve().parent.parent
X, R = ROOT / "data/xai", ROOT / "data/results"
KEY = {"qwen2.5-coder-1.5b": "A", "qwen2.5-coder-3b": "B", "qwen2.5-coder-7b": "C"}
BS, NL = chr(92), chr(10)


def main():
    ex = pd.read_csv(R / "exec_merged.csv")
    ex = ex[(ex.condition == "DIRECT") & (ex.status != "harness_error")]
    mac = ["% auto-generated by scripts/xai_numbers.py - do not edit",
           BS + "newcommand{" + BS + "XN}[3]{" + BS + "csname xn@#1@#2@#3" + BS + "endcsname}"]

    def d(m, v, f, val):
        mac.append(BS + "expandafter" + BS + "def" + BS + "csname xn@%s@%s@%s" % (m, v.replace("_", ""), f) + BS + "endcsname{%s}" % val)
    for model, k in KEY.items():
        p = X / f"xai_{model}.jsonl"
        if not p.exists():
            continue
        df = pd.read_json(p, lines=True)
        en = df[df.variant == "EN"].set_index("task_id")
        for v in sorted(set(df.variant)):
            g = df[df.variant == v].set_index("task_id")
            d(k, v, "sig", f"{100 * g.attr_signature.mean():.0f}")
            d(k, v, "desc", f"{100 * g.attr_description.mean():.0f}")
            if v != "EN":
                d(k, v, "nll", f"{(g.nll - en.nll.reindex(g.index)).median():.3f}")
        h = X / f"xai_{model}_hidden.npz"
        if h.exists():
            z = np.load(h, allow_pickle=True)
            keys = [str(x) for x in z["keys"]]
            idx = {x: i for i, x in enumerate(keys)}
            last = z["last"].astype(np.float32)
            nl = last.shape[1]
            tasks = sorted({x.split("|")[0] for x in keys})

            def cos(a, b):
                return (a * b).sum(-1) / (np.linalg.norm(a, axis=-1) * np.linalg.norm(b, axis=-1) + 1e-9)
            per = {}
            for v in sorted({x.split("|")[1] for x in keys} - {"EN"}):
                ts = [t for t in tasks if f"{t}|EN" in idx and f"{t}|{v}" in idx]
                c = np.stack([cos(last[idx[f"{t}|EN"]], last[idx[f"{t}|{v}"]]) for t in ts])[:, int(0.75 * nl):].mean(1)
                per[v] = dict(zip(ts, c))
                d(k, v, "cos", f"{c.mean():.2f}")
            e = ex[ex.model_id == model]
            pv = e.groupby(["task_id", "variant"]).functional_pass.mean().unstack()
            if "BN" in per and "BN" in pv:
                t = [x for x in per["BN"] if x in pv.index and not np.isnan(pv.loc[x, "BN"])]
                drop = (pv.loc[t, "EN"] - pv.loc[t, "BN"]).values
                rho, pval = sps.spearmanr([per["BN"][x] for x in t], drop)
                d(k, "all", "rho", f"{rho:.2f}".replace("-", "$-$"))
                d(k, "all", "rhop", f"{pval:.2f}")
                d(k, "all", "n", str(len(t)))
    (ROOT / "paper/xai_numbers.tex").write_text(NL.join(mac) + NL, encoding="utf-8")
    print(NL.join(m for m in mac if "@A@" in m or "@B@" in m)[:2500])


if __name__ == "__main__":
    main()
