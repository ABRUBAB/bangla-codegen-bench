#!/usr/bin/env python3
"""Translation-audit tooling.

  python scripts/audit_tools.py llm-stats      -> paper/llm_audit_numbers.tex  (AI-audit statistics, always reportable)
  python scripts/audit_tools.py build          -> data/audit/review_annotator{1,2}.xlsx  (human REVIEW workbooks)
  python scripts/audit_tools.py ingest A.xlsx B.xlsx -> paper/audit_numbers.tex (human review statistics; sets \\auditdonetrue)

Honest labelling: the first-stage audit of every rendering was performed by Claude Opus agents (data/audit/llm_opus_*.json).
The review workbooks contain those AI judgements pre-filled in grey columns plus empty yellow columns for a human reviewer.
The paper reports a human-verification claim ONLY after `ingest` has been run on workbooks that people actually completed.
"""
import glob
import json
import random
import statistics as st
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from bcb.stats import cohens_kappa  # noqa: E402

AUD = ROOT / "data/audit"


def load_llm():
    items = []
    for f in sorted(AUD.glob("llm_opus_*.json")):
        items += json.loads(f.read_text(encoding="utf-8"))
    return items


def load_tasks():
    t = {}
    for name in ("functional", "security"):
        for l in (ROOT / "data/tasks" / f"{name}.jsonl").read_text(encoding="utf-8").splitlines():
            if l.strip():
                r = json.loads(l); t[r["task_id"]] = r
    for p in sorted((ROOT / "data/tasks/_new").glob("*.jsonl")) if (ROOT / "data/tasks/_new").exists() else []:
        for l in p.read_text(encoding="utf-8").splitlines():
            if l.strip():
                r = json.loads(l); t.setdefault(r["task_id"], r)
    return t


def llm_stats():
    items = load_llm()
    out = ["% auto-generated by scripts/audit_tools.py llm-stats (AI audit by Claude Opus; pre-fix ratings)"]
    out.append(f"\\newcommand{{\\llmAuditN}}{{{len(items)}}}")
    tot_issue = 0
    for r, tag in (("bn", "Bn"), ("bn_mix", "Mix"), ("banglish", "Bl"), ("es", "Es")):
        xs = [a for a in items if a["rendering"] == r]
        if not xs:
            continue
        nat = st.mean(a["naturalness"] for a in xs)
        y = sum(a["meaning"] == "Y" for a in xs); mi = sum(a["meaning"] == "MINOR" for a in xs); n = sum(a["meaning"] == "N" for a in xs)
        fixed = sum(1 for a in xs if a.get("fix", "").strip())
        out += [f"\\newcommand{{\\llmN{tag}}}{{{len(xs)}}}", f"\\newcommand{{\\llmNat{tag}}}{{{nat:.2f}}}",
                f"\\newcommand{{\\llmY{tag}}}{{{y}}}", f"\\newcommand{{\\llmMinor{tag}}}{{{mi}}}", f"\\newcommand{{\\llmMajor{tag}}}{{{n}}}",
                f"\\newcommand{{\\llmFixed{tag}}}{{{fixed}}}"]
        tot_issue += fixed
    out.append(f"\\newcommand{{\\llmFixedTotal}}{{{tot_issue}}}")
    (ROOT / "paper/llm_audit_numbers.tex").write_text("\n".join(out) + "\n")
    print("\n".join(out))


def build():
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.worksheet.datavalidation import DataValidation
    items, tasks = load_llm(), load_tasks()
    applied = {(a["task_id"], a["rendering"]) for f in AUD.glob("applied_fixes_*.json") for a in json.loads(f.read_text(encoding="utf-8"))}
    rng = random.Random(42)
    ids_f = sorted(t for t in tasks if t.startswith("F")); ids_s = sorted(t for t in tasks if t.startswith("S"))
    sample_tasks = set(rng.sample(ids_f, min(40, len(ids_f))) + rng.sample(ids_s, min(20, len(ids_s))))
    rng2 = random.Random(43)
    es_sample = set(rng2.sample(ids_f, min(40, len(ids_f))) + rng2.sample(ids_s, min(20, len(ids_s))))
    rows = []
    for a in items:
        t = tasks.get(a["task_id"])
        if not t:
            continue
        key = a["rendering"]
        in_sample = (key != "es" and a["task_id"] in sample_tasks) or (key == "es" and a["task_id"] in es_sample)
        rows.append(dict(task_id=a["task_id"], rendering=key, en=t["description"]["en"], text=t["description"][key],
                         llm_meaning=a["meaning"], llm_nat=a["naturalness"], llm_reg=a["register_ok"], llm_issues=a["issues"],
                         fixed="Y" if (a["task_id"], key) in applied else "", in_sample=in_sample))
    head = ["item_id", "task_id", "rendering", "ENGLISH (original)", "RENDERING (current text)", "AI meaning", "AI naturalness",
            "AI register_ok", "AI issues", "AI fix applied", "human_meaning (Y/MINOR/N)", "human_naturalness (1-5)",
            "human_agrees_with_AI (Y/N)", "human_comment", "annotator"]
    instr = ["BanglaCodeBench - human REVIEW of AI-audited renderings",
             "",
             "Grey columns are the judgements of an AI auditor (Claude Opus). They are PRE-FILLED SUGGESTIONS, not human data.",
             "Your task (yellow columns): read ENGLISH and RENDERING and give YOUR OWN judgement; then say whether you agree with the AI.",
             "meaning: Y = same requirements; MINOR = wording differs, same implementation; N = a requirement is missing/added/changed.",
             "naturalness: 1 (machine-like) .. 5 (fully natural for that register: BN formal Bangla / BN_MIX code-mixed / BANGLISH romanized / ES Spanish).",
             "Work independently of the other reviewer. Start with sheet 'Review_sample' (the pre-registered sample); 'All_items' is optional.",
             "Only judgements that you really made may be reported as human review in the paper. Save the file and run scripts/audit_tools.py ingest."]
    for k, seed in ((1, 101), (2, 202)):
        wb = Workbook(); ws0 = wb.active; ws0.title = "Instructions"
        for i, line in enumerate(instr, 1):
            ws0.cell(i, 1, line).font = Font(bold=(i == 1), size=13 if i == 1 else 11)
        ws0.column_dimensions["A"].width = 150
        for sheet, sel in (("Review_sample", [r for r in rows if r["in_sample"]]), ("All_items", rows)):
            ws = wb.create_sheet(sheet); ws.append(head)
            order = sel[:]; random.Random(seed).shuffle(order)
            for n, r in enumerate(order, 1):
                ws.append([f"R{n:04d}", r["task_id"], r["rendering"], r["en"], r["text"], r["llm_meaning"], r["llm_nat"], r["llm_reg"],
                           r["llm_issues"], r["fixed"], None, None, None, None, f"annotator{k}"])
            for i, w in enumerate([8, 8, 10, 55, 55, 10, 10, 10, 40, 9, 16, 14, 14, 30, 11]):
                ws.column_dimensions[chr(65 + i)].width = w
            for c in ws[1]:
                c.font = Font(bold=True, color="FFFFFF"); c.fill = PatternFill("solid", fgColor="3C5488")
            for row in ws.iter_rows(min_row=2):
                for c in row:
                    c.alignment = Alignment(wrap_text=True, vertical="top")
                for c in row[5:10]:
                    c.fill = PatternFill("solid", fgColor="EEEEEE")
                for c in row[10:14]:
                    c.fill = PatternFill("solid", fgColor="FFF8E1")
            n = len(order) + 1
            for formula, col in (('"Y,MINOR,N"', "K"), ('"1,2,3,4,5"', "L"), ('"Y,N"', "M")):
                dv = DataValidation(type="list", formula1=formula, allow_blank=True); ws.add_data_validation(dv); dv.add(f"{col}2:{col}{n}")
            ws.freeze_panes = "F2"
        wb.save(AUD / f"review_annotator{k}.xlsx")
    print("wrote review workbooks;", sum(r["in_sample"] for r in rows), "sample items,", len(rows), "total")


def ingest(pa, pb):
    import pandas as pd
    def load(p):
        d = pd.read_excel(p, sheet_name="Review_sample")
        d["rendering"] = d["rendering"].astype(str)
        return d.set_index(["task_id", "rendering"])
    a, b = load(pa), load(pb)
    col = "human_meaning (Y/MINOR/N)"; nat = "human_naturalness (1-5)"; ag = "human_agrees_with_AI (Y/N)"
    idx = a.index.intersection(b.index)
    a, b = a.loc[idx], b.loc[idx]
    ok = a[col].notna() & b[col].notna()
    a, b = a[ok], b[ok]
    n = len(a)
    kappa_hh = cohens_kappa(a[col], b[col])
    kappa_ha = cohens_kappa(a[col], a["AI meaning"]); kappa_hb = cohens_kappa(b[col], b["AI meaning"])
    agree_ai = float(np.mean([(a[ag] == "Y").mean(), (b[ag] == "Y").mean()]))
    nat_mean = float(np.nanmean(np.r_[a[nat].astype(float), b[nat].astype(float)]))
    major = float(((a[col] == "N") | (b[col] == "N")).mean())
    tex = ["\\auditdonetrue", f"\\newcommand{{\\auditN}}{{{n}}}", f"\\newcommand{{\\auditKappa}}{{{kappa_hh:.2f}}}",
           f"\\newcommand{{\\auditKappaAI}}{{{(kappa_ha + kappa_hb) / 2:.2f}}}", f"\\newcommand{{\\auditAgreeAI}}{{{100 * agree_ai:.1f}}}",
           f"\\newcommand{{\\auditNatMean}}{{{nat_mean:.2f}}}", f"\\newcommand{{\\auditMajor}}{{{100 * major:.1f}}}"]
    (ROOT / "paper/audit_numbers.tex").write_text("\n".join(tex) + "\n")
    print("\n".join(tex))


if __name__ == "__main__":
    cmd = sys.argv[1]
    {"llm-stats": llm_stats, "build": build}.get(cmd, lambda: ingest(sys.argv[2], sys.argv[3]))()
