#!/usr/bin/env python3
"""Interventional analysis: is the Bangla penalty a language effect or a token-length effect?  (see bcb/causal.py)

Per model, functional pass rate (task-level mean over samples, direct arm) of
  EN, EN_PAD (English padded to the Bangla token count), HYB33, HYB67 (a third / two thirds of the sentences in Bangla),
  BN_DESC (all description sentences in Bangla, English wrapper) and BN (Bangla description and wrapper).
Differences to EN are paired by task, with task-cluster bootstrap CIs and Wilcoxon p-values.
Reads data/results/exec_merged.csv; writes data/results/tab_causal.csv, paper/causal_numbers.tex and figures/fig_causal.{pdf,png}."""
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))
from bcb.stats import cluster_bootstrap_diff, wilcoxon_paired  # noqa: E402
from figstyle import MODEL_LABEL, MODEL_ORDER, NPG, save, setup  # noqa: E402

KEY = {"qwen2.5-coder-1.5b": "A", "qwen2.5-coder-3b": "B", "qwen2.5-coder-7b": "C", "deepseek-coder-6.7b": "D",
       "qwen3-8b": "E", "tigercoder-1b": "F", "qwen3.8-27b": "G", "qwen2.5-coder-14b": "H", "gemma-4-31b": "I",
       "ministral-3-14b": "J", "qwen2.5-coder-7b-q4": "K", "gemma-4-e4b": "L"}
VARS = ["EN", "EN_PAD", "HYB33", "HYB67", "BN_DESC", "BN"]


def load():
    ex = pd.read_csv(ROOT / "data/results/exec_merged.csv")
    ex = ex[(ex.condition == "DIRECT") & (ex.status != "harness_error") & (ex.kind == "functional") & ex.variant.isin(VARS)]
    return ex.groupby(["model_id", "task_id", "variant"]).functional_pass.mean().reset_index()


def main():
    pt = load()
    rows = []
    for m, g in pt.groupby("model_id"):
        piv = g.pivot(index="task_id", columns="variant", values="functional_pass")
        if "EN_PAD" not in piv or "BN_DESC" not in piv:
            continue  # causal controls not generated for this model yet
        for v in VARS:
            if v == "EN" or v not in piv:
                continue
            ok = piv[["EN", v]].dropna()
            if len(ok) < 10:
                continue
            a, b = ok[v].to_numpy(), ok["EN"].to_numpy()
            d, lo, hi = cluster_bootstrap_diff(a, b)
            p = wilcoxon_paired(a, b)[1] if np.any(a != b) else 1.0
            rows.append({"model_id": m, "variant": v, "n_tasks": len(ok), "pass_pct": 100 * a.mean(), "en_pct": 100 * b.mean(),
                         "delta_pp": 100 * d, "lo": 100 * lo, "hi": 100 * hi, "p": p})
        # all-Bangla description on exactly the tasks that have the hybrid variants (comparable end point of the dose-response)
        if "HYB33" in piv and "HYB67" in piv:
            sub = piv.dropna(subset=["EN", "HYB33", "HYB67", "BN_DESC"])
            if len(sub) >= 10:
                a, b = sub["BN_DESC"].to_numpy(), sub["EN"].to_numpy()
                d, lo, hi = cluster_bootstrap_diff(a, b)
                p = wilcoxon_paired(a, b)[1] if np.any(a != b) else 1.0
                rows.append({"model_id": m, "variant": "BN_DESC_SUB", "n_tasks": len(sub), "pass_pct": 100 * a.mean(),
                             "en_pct": 100 * b.mean(), "delta_pp": 100 * d, "lo": 100 * lo, "hi": 100 * hi, "p": p})
    tab = pd.DataFrame(rows)
    if tab.empty:
        print("no model has the causal-control variants yet")
        return
    tab.to_csv(ROOT / "data/results/tab_causal.csv", index=False)
    mac = ["% auto-generated by scripts/causal_analysis.py - do not edit", r"\newcommand{\CZ}[3]{\csname cz@#1@#2@#3\endcsname}"]
    for _, r in tab.iterrows():
        k, v = KEY.get(r.model_id, r.model_id), r.variant.replace("_", "")
        for f, val in (("pass", f"{r.pass_pct:.1f}"), ("d", f"{r.delta_pp:+.1f}".replace("-", "$-$")), ("lo", f"{r.lo:.1f}"), ("hi", f"{r.hi:.1f}"),
                       ("p", f"{r.p:.3f}"), ("n", f"{int(r.n_tasks)}"), ("en", f"{r.en_pct:.1f}")):
            mac.append(r"\expandafter\def\csname cz@%s@%s@%s\endcsname{%s}" % (k, v, f, val))
    (ROOT / "paper/causal_numbers.tex").write_text("\n".join(mac) + "\n", encoding="utf-8")

    setup()
    models = [m for m in MODEL_ORDER + sorted(set(tab.model_id) - set(MODEL_ORDER)) if m in set(tab.model_id)]
    fig, axs = plt.subplots(1, 2, figsize=(7.2, 2.9), gridspec_kw={"width_ratios": [1.1, 1]})
    ax = axs[0]
    w = 0.26
    for j, (v, c, lab) in enumerate((("EN_PAD", NPG["slate"], "EN padded to BN length"), ("BN_DESC", NPG["red"], "BN description"))):
        d = [tab[(tab.model_id == m) & (tab.variant == v)] for m in models]
        y = [x.delta_pp.iloc[0] if len(x) else np.nan for x in d]
        e = [[(x.delta_pp.iloc[0] - x.lo.iloc[0]) if len(x) else 0 for x in d], [(x.hi.iloc[0] - x.delta_pp.iloc[0]) if len(x) else 0 for x in d]]
        ax.bar(np.arange(len(models)) + (j - 0.5) * w, y, w, yerr=e, color=c, label=lab, capsize=1.5, linewidth=0, error_kw={"lw": 0.7})
    ax.axhline(0, color="grey", lw=0.7)
    ax.set_xticks(range(len(models)))
    ax.set_xticklabels([MODEL_LABEL.get(m, m).replace("Qwen2.5-Coder ", "Q2.5-C ") for m in models], rotation=30, ha="right", fontsize=6.5)
    ax.set_ylabel("Pass@1 change vs EN (pp)")
    ax.legend(fontsize=6, loc="lower left")
    ax.text(-0.17, 1.04, "(a)", transform=ax.transAxes, fontweight="bold", fontsize=9)
    ax = axs[1]
    xs = {"EN": 0, "HYB33": 1 / 3, "HYB67": 2 / 3, "BN_DESC_SUB": 1}
    for i, m in enumerate(models):
        s = tab[tab.model_id == m].set_index("variant")
        pts = [(xs[v], s.loc[v, "pass_pct"]) for v in ("HYB33", "HYB67", "BN_DESC_SUB") if v in s.index]
        if not pts or "HYB33" not in s.index:
            continue
        en = s.loc["HYB33", "en_pct"]
        ax.plot([0] + [p[0] for p in pts], [en] + [p[1] for p in pts], marker="o", ms=3, lw=1, label=MODEL_LABEL.get(m, m).replace("Qwen2.5-Coder ", "Q2.5-C "))
    ax.set_xlabel("share of description sentences in Bangla")
    ax.set_ylabel("Pass@1 (%)")
    ax.legend(fontsize=5.5)
    ax.text(-0.2, 1.04, "(b)", transform=ax.transAxes, fontweight="bold", fontsize=9)
    fig.subplots_adjust(wspace=0.4, bottom=0.27)
    save(fig, "fig_causal", ROOT / "figures")
    print(tab.round(2).to_string())


if __name__ == "__main__":
    main()
