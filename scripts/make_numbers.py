#!/usr/bin/env python3
"""results tables -> paper/numbers.tex (LaTeX macros) + generated LaTeX tables.

Usage in the paper:  \\N{pf-qC-BN}  (functional Pass@1 %, Qwen2.5-Coder-7B, formal Bangla)
Keys: <kind>-<model code>-<variant code>; model codes and variant codes below. Every number quoted in the text must come
from here so that text cannot drift from the data."""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
R = Path(os.environ.get("BCB_RESULTS", ROOT / "data/results"))
PAPER = Path(os.environ.get("BCB_PAPER_OUT", ROOT / "paper"))
MC = {"qwen2.5-coder-1.5b": "qA", "qwen2.5-coder-3b": "qB", "qwen2.5-coder-7b": "qC", "deepseek-coder-6.7b": "dsA",
      "qwen3-8b": "qwT", "tigercoder-1b": "tgA", "tigercoder-9b": "tgB", "gemini-3.1-flash-lite": "gem"}
VC = {"EN": "EN", "EN_TYPO": "ENTYPO", "BN": "BN", "BN_SPELL": "BNSPELL", "BN_MIX": "BNMIX", "BN_TYPO": "BNTYPO",
      "BANGLISH": "BL", "ES": "ES", "ES_TYPO": "ESTYPO", "ID_ONLY": "ID"}
MODEL_TXT = {"qwen2.5-coder-1.5b": "Qwen2.5-Coder 1.5B", "qwen2.5-coder-3b": "Qwen2.5-Coder 3B", "qwen2.5-coder-7b": "Qwen2.5-Coder 7B",
             "deepseek-coder-6.7b": "DeepSeek-Coder 6.7B", "qwen3-8b": "Qwen3 8B", "tigercoder-1b": "TigerCoder 1B",
             "tigercoder-9b": "TigerCoder 9B", "gemini-3.1-flash-lite": "Gemini 3.1 Flash-Lite"}
ORDER = list(MC)
lines = ["% auto-generated by scripts/make_numbers.py - do not edit",
         "\\newcommand{\\N}[1]{\\csname n@#1\\endcsname}"]


NL = chr(10)
BS = chr(92)


def _counts():
    tasks = []
    for name in ("functional", "security"):
        tasks += [json.loads(l) for l in (ROOT / f"data/tasks/{name}.jsonl").read_text(encoding="utf-8").split(NL) if l.strip()]
    prompts = [l for l in (ROOT / "data/prompts/prompts.jsonl").read_text(encoding="utf-8").split(NL) if l.strip()]
    sec = [t for t in tasks if t["kind"] == "security"]
    allcwe = {c for t in sec for c in t.get("cwe_ids", [])}
    models = [m for m in ORDER if (ROOT / "data/generations" / m).exists()]
    c = {"NTasks": len(tasks), "NFunc": len(tasks) - len(sec), "NSec": len(sec), "NCwe": len({t["category"] for t in sec}),
         "NCweAll": len(allcwe), "NPrompts": f"{len(prompts):,}", "NModels": len(models)}
    for k, v in c.items():
        lines.append(BS + "newcommand{" + BS + k + "}{" + str(v) + "}")
    (ROOT / "figures/workflow_numbers.json").write_text(json.dumps({
        "n_tasks": c["NTasks"], "n_func": c["NFunc"], "n_sec": c["NSec"], "n_cwe": c["NCwe"], "n_prompts": len(prompts),
        "n_models": max(c["NModels"], 7), "n_tokenizers": 9, "n_generations": f"~{round(len(prompts) * 3 * max(c['NModels'], 7) * 1.4 / 1000)}k"}))


def d(key, val):
    lines.append(f"\\expandafter\\def\\csname n@{key}\\endcsname{{{val}}}")


def pct(x, n=1):
    return f"{100 * x:.{n}f}"


def sgn(x, n=1):
    return f"{100 * x:+.{n}f}".replace("-", "$-$")


def rd(name):
    p = R / name
    if not p.exists():
        return None
    try:
        t = pd.read_csv(p)
    except pd.errors.EmptyDataError:
        return None
    return t if len(t) else None


def pvalue(p):
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def models_in(df):
    return [m for m in ORDER if m in set(df["model_id"])]


tabs = {}
_counts()
# ---------------------------------------------------------------- Pass@1 cells
for name, tag in (("tab_pass_functional.csv", "pf"), ("tab_pass_security_tasks.csv", "ps"), ("tab_pass_all.csv", "pa")):
    t = rd(name)
    if t is None:
        continue
    tabs[tag] = t
    for _, r in t.iterrows():
        key = f"{MC[r.model_id]}-{VC.get(r.variant, r.variant)}" + ("" if r.condition == "DIRECT" else "-TF")
        d(f"{tag}-{key}", pct(r["mean"])); d(f"{tag}lo-{key}", pct(r["lo"])); d(f"{tag}hi-{key}", pct(r["hi"]))
    dd = t[t.condition == "DIRECT"]
    for v, g in dd.groupby("variant"):
        d(f"{tag}All-{VC.get(v, v)}", pct(g["mean"].mean()))

# ---------------------------------------------------------------- contrasts
for name, tag in (("tab_contrasts_functional.csv", "df"), ("tab_contrasts_security_tasks.csv", "ds"), ("tab_contrasts_all.csv", "da")):
    t = rd(name)
    if t is None:
        continue
    tabs[tag] = t
    for _, r in t.iterrows():
        key = f"{MC[r.model_id]}-{VC.get(r.variant, r.variant)}"
        d(f"{tag}-{key}", sgn(r["diff"])); d(f"{tag}lo-{key}", sgn(r["lo"])); d(f"{tag}hi-{key}", sgn(r["hi"]))
        d(f"{tag}p-{key}", pvalue(r["p_holm"]))
    for v, g in t.groupby("variant"):
        d(f"{tag}All-{VC.get(v, v)}", sgn(g["diff"].mean()))

# ---------------------------------------------------------------- security
t = rd("tab_security.csv")
if t is not None:
    tabs["sec"] = t
    for _, r in t.iterrows():
        key = f"{MC[r.model_id]}-{VC.get(r.variant, r.variant.replace('_HINT', 'H').replace('_', ''))}" + ("" if r.condition == "DIRECT" else "-TF")
        key = key.replace("EN_HINT", "ENH")
        d(f"V-{key}", pct(r["vuln_rate"])); d(f"Vlo-{key}", pct(r["vuln_lo"])); d(f"Vhi-{key}", pct(r["vuln_hi"])); d(f"SC-{key}", pct(r["SC"]))
    dd = t[t.condition == "DIRECT"]
    for v, g in dd.groupby("variant"):
        k = VC.get(v, v.replace("_", ""))
        d(f"VAll-{k}", pct(g["vuln_rate"].mean())); d(f"SCAll-{k}", pct(g["SC"].mean()))
ex = rd("exec_merged.csv")
if ex is not None:
    ex["functional_pass"] = ex["functional_pass"].astype(bool)
    d("nExec", f"{len(ex):,}")
    d("nHarnessErr", int((ex["status"] == "harness_error").sum()))
    d("nNoCode", int((ex["func_failure_type"] == "no_code").sum()))
    d("nModels", ex["model_id"].nunique())
    if "finish" in ex:
        d("truncPct", pct((ex["finish"] == "length").mean()))
    sec = ex[(ex.kind == "security") & ex.functional_pass & ex.exploit_pass.notna() & (ex.condition == "DIRECT")]
    d("VPooled", pct((sec.exploit_pass == False).mean()))  # noqa: E712
    d("nWorkingSec", f"{len(sec):,}")
    # hint ablation (pooled over models and tasks)
    for base, hint in (("EN", "EN_HINT"), ("BN", "BN_HINT"), ("BN_MIX", "BN_MIX_HINT"), ("BANGLISH", "BANGLISH_HINT"), ("ES", "ES_HINT")):
        b = sec[sec.variant == base]; h = sec[sec.variant == hint]
        if len(b) and len(h):
            vb, vh = (b.exploit_pass == False).mean(), (h.exploit_pass == False).mean()  # noqa: E712
            k = VC[base]
            d(f"hintV0-{k}", pct(vb)); d(f"hintV1-{k}", pct(vh)); d(f"hintD-{k}", sgn(vh - vb))
# ---------------------------------------------------------------- pooled GEE and matched security contrasts
t = rd("tab_pooled_gee.csv")
if t is not None:
    oc = {"pass_functional": "pf", "pass_security_tasks": "ps", "vulnerable_given_working": "vg"}
    for _, r in t.iterrows():
        k = f"pg{oc[r.outcome]}-{VC.get(r.variant, r.variant)}"
        d(f"{k}-OR", f"{r.OR:.2f}"); d(f"{k}-lo", f"{r.OR_lo:.2f}"); d(f"{k}-hi", f"{r.OR_hi:.2f}"); d(f"{k}-p", pvalue(r.p_holm))
t = rd("tab_security_paired.csv")
if t is not None:
    for _, r in t.iterrows():
        k = f"sp-{MC[r.model_id]}-{VC.get(r.variant, r.variant)}"
        d(k, sgn(r["diff"])); d(k + "-lo", sgn(r["lo"])); d(k + "-hi", sgn(r["hi"])); d(k + "-p", pvalue(r["p_holm"])); d(k + "-n", int(r["n_tasks"]))
    for v, g in t.groupby("variant"):
        d(f"spAll-{VC.get(v, v)}", sgn(g["diff"].mean()))
# ---------------------------------------------------------------- static vs dynamic
t = rd("tab_static_vs_dynamic.csv")
if t is not None:
    for _, r in t.iterrows():
        k = "rel" if r.static_rule == "bandit_relevant" else "any"
        d(f"sd-prec-{k}", pct(r.precision)); d(f"sd-rec-{k}", pct(r.recall)); d(f"sd-kappa-{k}", f"{r.kappa:.2f}")
        d(f"sd-spdf-{k}", pct(r.spdf_rate)); d(f"sd-n-{k}", int(r.n)); d(f"sd-TP-{k}", int(r.TP)); d(f"sd-FN-{k}", int(r.FN))
        d(f"sd-FP-{k}", int(r.FP)); d(f"sd-TN-{k}", int(r.TN))
# ---------------------------------------------------------------- mitigation
t = rd("tab_mitigation.csv")
if t is not None:
    tabs["mit"] = t
    for _, r in t.iterrows():
        key = f"{MC[r.model_id]}-{VC[r.variant]}"
        d(f"mit-d-{key}", sgn(r["delta"])); d(f"mit-lo-{key}", sgn(r["lo"])); d(f"mit-hi-{key}", sgn(r["hi"]))
        d(f"mit-p-{key}", pvalue(r["p_holm"])); d(f"mit-tok-{key}", f"{r.token_ratio_median:.2f}")
        if not np.isnan(r.gap_closed_frac):
            d(f"mit-gap-{key}", pct(r.gap_closed_frac, 0))
# ---------------------------------------------------------------- tokens
t = rd("tab_token_ratio_median.csv")
if t is not None:
    tmap = {"GPT-4 (cl100k)": "cl100k", "GPT-4o (o200k)": "o200k", "Qwen2.5 (151k)": "qwen25", "Qwen3 (151k)": "qwen3",
            "DeepSeek-Coder (32k)": "dsc", "DeepSeek-V2 (100k)": "dsv2", "TigerCoder (262k)": "tiger", "Llama-3.1 (128k)": "llama3",
            "Mistral-v0.3 (33k)": "mistral"}
    t = t.set_index(t.columns[0])
    for tok, row in t.iterrows():
        for v, val in row.items():
            d(f"tr-{tmap.get(tok, tok)}-{VC.get(v, v)}", f"{val:.2f}")
# ---------------------------------------------------------------- XAI
p = R / "xai_model_cv.json"
if p.exists():
    cv = json.loads(p.read_text())
    for k, v in cv.items():
        d("cv-" + {"task+model": "base", "+variant": "var", "+variant+tokenization": "tok"}.get(k, k), f"{v['auroc_mean']:.3f}")
p = R / "xai_alignment_corr.json"
if p.exists():
    a = json.loads(p.read_text()); d("align-rho", f"{a['spearman_rho']:.2f}"); d("align-p", pvalue(a["p"])); d("align-n", a["n"])
t = rd("tab_cost_per_success.csv")
if t is not None:
    tabs["cps"] = t
    for _, r in t.iterrows():
        k = f"{MC[r.model_id]}-{VC.get(r.variant, r.variant.replace('_', ''))}" + ("" if r.condition == "DIRECT" else "-TF")
        if not np.isnan(r.get("tokens_per_secure_correct", np.nan)):
            d(f"cps-{k}", f"{r.tokens_per_secure_correct:,.0f}")
        if not np.isnan(r.get("tokens_per_correct_func", np.nan)):
            d(f"cpf-{k}", f"{r.tokens_per_correct_func:,.0f}")
    dd = t[t.condition == "DIRECT"]
    for v, g in dd.groupby("variant"):
        k = VC.get(v, v.replace("_", ""))
        if g["tokens_per_secure_correct"].notna().any():
            d(f"cpsAll-{k}", f"{g['tokens_per_secure_correct'].mean():,.0f}")
            en = dd[dd.variant == "EN"].set_index("model_id")["tokens_per_secure_correct"]
            ratio = (g.set_index("model_id")["tokens_per_secure_correct"] / en).dropna()
            if len(ratio):
                d(f"cpsRatio-{k}", f"{ratio.mean():.1f}")
(PAPER / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(len(lines), "macros written")


# ================================================================ tables
def write_table(name, body):
    (PAPER / name).write_text(body, encoding="utf-8")


def cell_pass(tag, m, v, tf=False):
    return f"\\N{{{tag}-{MC[m]}-{VC[v]}{'-TF' if tf else ''}}}"


t = tabs.get("pf")
if t is not None:
    models = models_in(t)
    vs = ["EN", "EN_TYPO", "BN", "BN_SPELL", "BN_MIX", "BN_TYPO", "BANGLISH", "ES", "ES_TYPO", "ID_ONLY"]
    have = set(t[t.condition == "DIRECT"].variant)
    vs = [v for v in vs if v in have]
    rows = ["\\begin{tabular}{@{}l" + "r" * len(vs) + "@{}}", "\\toprule",
            "Model & " + " & ".join(f"\\texttt{{{v.replace('_', chr(92) + '_')}}}" for v in vs) + "\\\\", "\\midrule"]
    for m in models:
        rows.append(MODEL_TXT[m] + " & " + " & ".join(cell_pass("pf", m, v) for v in vs) + "\\\\")
    rows += ["\\midrule", "Mean over models & " + " & ".join(f"\\N{{pfAll-{VC[v]}}}" for v in vs) + "\\\\", "\\bottomrule", "\\end{tabular}"]
    write_table("tab_pass_functional.tex", "\n".join(rows) + "\n")
t = tabs.get("sec")
if t is not None:
    models = models_in(t)
    vs = [v for v in ["EN", "BN", "BN_MIX", "BANGLISH", "ES", "ID_ONLY"] if v in set(t[t.condition == "DIRECT"].variant)]
    rows = ["\\begin{tabular}{@{}l" + "r" * len(vs) + "@{}}", "\\toprule",
            "Model & " + " & ".join(f"\\texttt{{{v.replace('_', chr(92) + '_')}}}" for v in vs) + "\\\\", "\\midrule"]
    for m in models:
        rows.append(MODEL_TXT[m] + " & " + " & ".join(f"\\N{{V-{MC[m]}-{VC[v]}}}" for v in vs) + "\\\\")
    rows += ["\\midrule", "Mean & " + " & ".join(f"\\N{{VAll-{VC[v]}}}" for v in vs) + "\\\\", "\\bottomrule", "\\end{tabular}"]
    write_table("tab_vuln.tex", "\n".join(rows) + "\n")
t = tabs.get("mit")
if t is not None:
    rows = ["\\begin{tabular}{@{}llrrrr@{}}", "\\toprule", "Model & Variant & Direct & Translate-first & $\\Delta$ (pp) [95\\% CI] & Token ratio\\\\", "\\midrule"]
    for m in models_in(t):
        for v in ["BN", "BN_MIX", "BANGLISH", "ES"]:
            if ((t.model_id == m) & (t.variant == v)).any():
                k = f"{MC[m]}-{VC[v]}"
                rows.append(f"{MODEL_TXT[m]} & \\texttt{{{v.replace('_', chr(92) + '_')}}} & \\N{{pf-{k}}} & \\N{{pf-{k}-TF}} & \\N{{mit-d-{k}}} [\\N{{mit-lo-{k}}}, \\N{{mit-hi-{k}}}] & \\N{{mit-tok-{k}}}$\\times$\\\\")
    rows += ["\\bottomrule", "\\end{tabular}"]
    write_table("tab_mitigation.tex", "\n".join(rows) + "\n")


t = tabs.get("cps")
if t is not None:
    BS = chr(92)
    cols = [("EN", "DIRECT"), ("BN", "DIRECT"), ("BN_MIX", "DIRECT"), ("BANGLISH", "DIRECT"), ("ES", "DIRECT"), ("BN", "TRANSLATE_FIRST"), ("BANGLISH", "TRANSLATE_FIRST")]
    have = {(r.variant, r.condition) for r in t.itertuples()}
    cols = [c for c in cols if c in have]
    head = " & ".join(BS + "texttt{" + v.replace("_", BS + "_") + "}" + (" (TF)" if c == "TRANSLATE_FIRST" else "") for v, c in cols)
    rows = [BS + "begin{tabular}{@{}l" + "r" * len(cols) + "@{}}", BS + "toprule", "Model & " + head + BS + BS, BS + "midrule"]
    for m in models_in(t):
        cells = []
        for v, c in cols:
            key = f"cps-{MC[m]}-{VC[v]}" + ("" if c == "DIRECT" else "-TF")
            cells.append(BS + "N{" + key + "}")
        rows.append(MODEL_TXT[m] + " & " + " & ".join(cells) + BS + BS)
    rows += [BS + "bottomrule", BS + "end{tabular}"]
    write_table("tab_cps.tex", NL.join(rows) + NL)
